"""BibTeX 生成 / 合并 / 去重，以及从 arXiv / DOI 收集元数据。

设计原则：
- 纯标准库 + httpx（项目已有依赖），不引入新依赖；
- 网络失败抛 :class:`CitationError`（带可操作建议），由工具层转成 ``ToolResult.failure``；
- 所有收集到的条目都能直接写入 ``refs.bib`` 并被 LaTeX 编译。
"""

from __future__ import annotations

import re
import xml.etree.ElementTree as ET
from dataclasses import dataclass, field
from pathlib import Path

BIB_KEY_RE = re.compile(r"@\s*(\w+)\s*\{\s*([^,\s]+)\s*,")
_ENTRY_SPLIT_RE = re.compile(r"(?=@\s*\w+\s*\{)")
_ATOM_NS = {"atom": "http://www.w3.org/2005/Atom"}


class CitationError(RuntimeError):
    """参考文献收集/解析失败（可读、可指导修复）。"""


@dataclass
class BibEntry:
    """一条 BibTeX 条目。"""

    entry_type: str
    key: str
    fields: dict[str, str] = field(default_factory=dict)

    def render(self) -> str:
        lines = [f"@{self.entry_type}{{{self.key},"]
        width = max((len(name) for name in self.fields), default=0)
        for name, value in self.fields.items():
            if value is None or value == "":
                continue
            lines.append(f"  {name.ljust(width)} = {{{value}}},")
        lines.append("}")
        return "\n".join(lines)


# ---------------------------------------------------------------------------
# 解析 / 渲染 / 去重
# ---------------------------------------------------------------------------


def parse_bibtex(text: str) -> list[BibEntry]:
    """解析 BibTeX 文本（宽松解析，保留字段原文）。"""
    entries: list[BibEntry] = []
    chunks = [chunk for chunk in _ENTRY_SPLIT_RE.split(text or "") if chunk.strip().startswith("@")]
    for chunk in chunks:
        header = re.match(r"@\s*(\w+)\s*\{\s*([^,\s]+)\s*,", chunk)
        if not header:
            continue
        entry_type = header.group(1).lower()
        key = header.group(2)
        body = chunk[header.end() :]
        braces = 0
        end_index = len(body)
        for index, char in enumerate(body):
            if char == "{":
                braces += 1
            elif char == "}":
                if braces == 0:
                    end_index = index
                    break
                braces -= 1
        body = body[:end_index]
        fields: dict[str, str] = {}
        field_re = re.compile(r"(\w[\w-]*)\s*=\s*(\{(?:[^{}]|\{[^{}]*\})*\}|\"[^\"]*\"|[^,\s]+)", re.S)
        for match in field_re.finditer(body):
            name = match.group(1).lower()
            raw_value = match.group(2).strip()
            if raw_value.startswith("{") and raw_value.endswith("}"):
                value = raw_value[1:-1]
            elif raw_value.startswith('"') and raw_value.endswith('"'):
                value = raw_value[1:-1]
            else:
                value = raw_value
            fields[name] = re.sub(r"\s+", " ", value).strip()
        entries.append(BibEntry(entry_type=entry_type, key=key, fields=fields))
    return entries


def render_bibtex(entries: list[BibEntry]) -> str:
    return "\n\n".join(entry.render() for entry in entries)


def dedupe_bibtex(text: str) -> str:
    """按 cite key 去重（保留第一次出现的条目）。"""
    seen: set[str] = set()
    kept: list[BibEntry] = []
    for entry in parse_bibtex(text):
        if entry.key in seen:
            continue
        seen.add(entry.key)
        kept.append(entry)
    return render_bibtex(kept)


def merge_bibtex(*texts: str) -> str:
    """合并多段 BibTeX 文本，按 cite key 去重。"""
    return dedupe_bibtex("\n\n".join(text or "" for text in texts))


def add_bibtex(entries: str, path: str | Path | None = None) -> Path:
    """把 ``entries`` 合并进 ``path``（默认当前目录 ``refs.bib``），去重后写回。"""
    if not (entries or "").strip():
        raise CitationError("没有可写入的 BibTeX 条目（entries 为空）")
    target = Path(path).expanduser() if path is not None else Path.cwd() / "refs.bib"
    target.parent.mkdir(parents=True, exist_ok=True)
    existing = target.read_text(encoding="utf-8") if target.exists() else ""
    merged = merge_bibtex(existing, entries)
    header = "" if existing.strip() else "% refs.bib — generated by SciForge\n\n"
    target.write_text(header + merged + "\n", encoding="utf-8")
    return target


def bib_keys(text: str) -> list[str]:
    """提取 BibTeX 文本中的全部 cite key。"""
    return [match.group(2) for match in BIB_KEY_RE.finditer(text or "")]


# ---------------------------------------------------------------------------
# 构造条目
# ---------------------------------------------------------------------------


def _key_from(title: str, authors: list[str], year: str) -> str:
    first_author = "anon"
    if authors:
        first = authors[0].split()[-1] if authors[0].split() else authors[0]
        first_author = re.sub(r"[^0-9a-zA-Z]", "", first).lower() or "anon"
    word = "paper"
    for token in re.findall(r"[0-9a-zA-Z]+", title or ""):
        if len(token) > 2 and token.lower() not in ("the", "and", "for", "with", "from"):
            word = token.lower()
            break
    return f"{first_author}{re.sub(r'[^0-9]', '', year) or '0000'}{word}"


def make_bibtex_entry(
    *,
    entry_type: str = "article",
    title: str,
    authors: list[str] | None = None,
    year: str = "",
    venue: str = "",
    doi: str = "",
    url: str = "",
    arxiv_id: str = "",
    key: str | None = None,
) -> str:
    """手工构造一条 BibTeX（工具/测试用）。"""
    authors = authors or []
    fields: dict[str, str] = {
        "title": (title or "Untitled").strip(),
        "author": " and ".join(authors) if authors else "Unknown",
    }
    if venue:
        if entry_type in ("inproceedings", "conference"):
            fields["booktitle"] = venue
        else:
            fields["journal"] = venue
    if year:
        fields["year"] = str(year)
    if doi:
        fields["doi"] = doi
    if url:
        fields["url"] = url
    if arxiv_id:
        fields.setdefault("eprint", arxiv_id)
        fields.setdefault("archiveprefix", "arXiv")
    entry = BibEntry(
        entry_type=entry_type,
        key=key or _key_from(title, authors, str(year or "")),
        fields=fields,
    )
    return entry.render()


