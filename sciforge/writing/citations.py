# arXiv / DOI 元数据收集
# ---------------------------------------------------------------------------


def _http_get(url: str, *, timeout: float = 30.0) -> str:
    """单点网络访问，测试里可 monkeypatch。"""
    import httpx

    headers = {"User-Agent": "SciForge/0.1 (+https://github.com/sddzlsc/SciForge)"}
    response = httpx.get(url, timeout=timeout, follow_redirects=True, headers=headers)
    response.raise_for_status()
    return response.text


def collect_from_arxiv(ids: list[str] | str, *, timeout: float = 30.0) -> str:
    """按 arXiv id 列表拉取元数据，返回 BibTeX 文本。"""
    if isinstance(ids, str):
        id_list = [part.strip() for part in ids.split(",") if part.strip()]
    else:
        id_list = [str(item).strip() for item in ids if str(item).strip()]
    if not id_list:
        raise CitationError("请提供至少一个 arXiv id，例如 2401.00001")
    url = (
        "https://export.arxiv.org/api/query?search_query=&start=0&max_results="
        f"{len(id_list)}&id_list={','.join(id_list)}"
    )
    try:
        xml_text = _http_get(url, timeout=timeout)
    except Exception as exc:  # noqa: BLE001 - 网络异常统一转可读错误
        raise CitationError(
            f"arXiv 元数据请求失败：{type(exc).__name__}: {exc}。"
            "请检查网络/代理；或直接提供 BibTeX 文本（entries 参数）。"
        ) from exc
    try:
        root = ET.fromstring(xml_text)
    except ET.ParseError as exc:
        raise CitationError(f"arXiv 返回内容无法解析（可能被限流）：{exc}") from exc
    entries: list[str] = []
    for node in root.findall("atom:entry", _ATOM_NS):
        title = " ".join((node.findtext("atom:title", default="", namespaces=_ATOM_NS) or "").split())
        published = node.findtext("atom:published", default="", namespaces=_ATOM_NS) or ""
        year = published[:4]
        authors = []
        for author_node in node.findall("atom:author", _ATOM_NS):
            name = author_node.findtext("atom:name", default="", namespaces=_ATOM_NS)
            if name:
                authors.append(" ".join(name.split()))
        entry_id = node.findtext("atom:id", default="", namespaces=_ATOM_NS) or ""
        arxiv_id = entry_id.rsplit("/", 1)[-1].split("v")[0] if entry_id else ""
        comment = node.findtext("atom:comment", default="", namespaces=_ATOM_NS) or ""
        venue = "arXiv preprint"
        if "accepted" in comment.lower() or "conference" in comment.lower():
            venue = comment.strip()
        entries.append(
            make_bibtex_entry(
                entry_type="article",
                title=title or "Untitled",
                authors=authors,
                year=year,
                venue=venue,
                url=f"https://arxiv.org/abs/{arxiv_id}" if arxiv_id else "",
                arxiv_id=arxiv_id,
            )
        )
    if not entries:
        raise CitationError(f"arXiv 未返回任何条目（id 是否正确？）：{', '.join(id_list)}")
    return "\n\n".join(entries)


def collect_from_doi(doi: str | list[str], *, timeout: float = 30.0) -> str:
    """按 DOI 从 Crossref 收集元数据，返回 BibTeX 文本。"""
    dois = [doi] if isinstance(doi, str) else list(doi)
    dois = [item.strip().removeprefix("https://doi.org/").removeprefix("doi:") for item in dois if item.strip()]
    if not dois:
        raise CitationError("请提供至少一个 DOI")
    entries: list[str] = []
    for item in dois:
        url = f"https://api.crossref.org/works/{item}"
        try:
            text = _http_get(url, timeout=timeout)
        except Exception as exc:  # noqa: BLE001
            raise CitationError(
                f"Crossref DOI 请求失败（{item}）：{type(exc).__name__}: {exc}。"
                "请检查 DOI 是否正确或稍后重试。"
            ) from exc
        import json

        try:
            message = json.loads(text)["message"]
        except Exception as exc:  # noqa: BLE001
            raise CitationError(f"Crossref 返回格式异常（{item}）：{exc}") from exc
        title = " ".join((message.get("title") or ["Untitled"])[0].split())
        authors = []
        for author in message.get("author") or []:
            name = f"{author.get('given', '')} {author.get('family', '')}".strip()
            if name:
                authors.append(name)
        year = ""
        for key in ("published-print", "published-online", "issued", "created"):
            parts = (message.get(key) or {}).get("date-parts")
            if parts and parts[0]:
                year = str(parts[0][0])
                break
        venue = (message.get("container-title") or message.get("publisher") or [""])[0]
        entry_type = "inproceedings" if message.get("type") in ("proceedings-article",) else "article"
        entries.append(
            make_bibtex_entry(
                entry_type=entry_type,
                title=title,
                authors=authors,
                year=year,
                venue=venue,
                doi=item,
                url=message.get("URL") or "",
            )
        )
    return "\n\n".join(entries)


